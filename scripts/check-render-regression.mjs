// Proves that a change to src/render (or src/components/Canvas) does not silently rewrite
// artwork that customers have already saved. Run it BEFORE anything renderer-related goes
// live -- render-service deploy, frontend push, thumbnail backfill.
//
//   node scripts/check-render-regression.mjs                # vs the last commit
//   node scripts/check-render-regression.mjs --base v9-tag  # vs any git ref
//   node scripts/check-render-regression.mjs --allow-stars  # star-layer changes are intended
//
// Exit 0 = every stored design still composes exactly as it did. Exit 1 = something moved.
//
// WHY THIS EXISTS (2026-08-02, and it was a live incident, not a hypothetical). The star
// field rework raised the per-tier star counts. A star costs THREE rng() draws -- size, x,
// y -- so that was +876 draws taken from the SHARED sequence, sitting upstream of
// generateArtwork's geometryChance and overlayChance. Those two then read different numbers.
// Result: of 45 real gallery designs, 13 lost their geometry layer outright. Aaron caught it
// on the live site -- "the recent render change has completely destroyed the existing
// artwork" -- and the only reason it looked survivable is that 21 of the remaining designs
// carry settings.geometry.chance = 1, which passes regardless of the draw. With real
// customers holding saved designs, that would have been catastrophic rather than embarrassing.
//
// WHAT THE EXISTING CHECKS DID NOT CATCH, which is the whole point:
//
//   - "Composition is identical ACROSS SIZES for a seed" was verified, passed, and is the
//     invariant this project usually worries about (mockup-equals-print). It is orthogonal.
//     A change can be perfectly size-invariant and still rewrite every stored design.
//   - "GENERATOR_VERSION was bumped" protects nothing. generateArtwork never branches on the
//     version and no code path renders a previous one, so a stored design is ALWAYS
//     regenerated by whatever is in the bundle. The version is a record of what a design was
//     saved under, not a rendering instruction.
//   - Rendering a handful of fresh seeds and liking the result says nothing either: fresh
//     seeds have no prior appearance to preserve.
//
// The only thing that catches it is comparing OLD code against NEW code on the REAL stored
// rows, which is what this does.
//
// THE RULE IT ENFORCES: a change meant to affect one layer must not draw from the shared rng
// stream at all. Give it its own stream -- makeRng(`${seed}-<thing>`) -- as
// expandMonochromePalette (`-palette`), generateLabelMark (`-label`) and GenerateStarField
// (`-stars`) all do. If you must touch the shared stream, this check will fail and you have
// to decide, deliberately and out loud, that rewriting everyone's saved art is acceptable.

import { execSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const args = process.argv.slice(2);
const flag = (name, fallback = null) => {
  const hit = args.find(a => a.startsWith(`--${name}=`));
  if (hit) return hit.split('=').slice(1).join('=');
  const i = args.indexOf(`--${name}`);
  return i !== -1 && args[i + 1] && !args[i + 1].startsWith('--') ? args[i + 1] : fallback;
};
const BASE = flag('base', 'HEAD~1');
const ALLOW_STARS = args.includes('--allow-stars');
const SIZES = [
  [3840, 2160], // studio default
  [2000, 2000], // thumbnail density floor (square)
  [3150, 5550] // a real print file
];

// Read the env the frontend already uses -- these designs are public-readable, so the anon
// key is enough and no service-role secret is needed to run this.
const envPath = path.join(REPO, '.env.local');
if (fs.existsSync(envPath)) {
  for (const line of fs.readFileSync(envPath, 'utf8').split('\n')) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m && !process.env[m[1]]) process.env[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
}
const SUPABASE_URL = process.env.SUPABASE_URL || process.env.VITE_SUPABASE_URL;
const ANON = process.env.VITE_SUPABASE_ANON_KEY;
if (!SUPABASE_URL || !ANON) {
  console.error('Need VITE_SUPABASE_URL and VITE_SUPABASE_ANON_KEY (from .env.local or the env).');
  process.exit(1);
}

// Everything that defines the piece EXCEPT the star field. secondBlend is excluded because
// that IS the star field's blend mode -- a star-layer property, not part of the rest.
const COMPOSITION_FIELDS = [
  'gradientBackgroundConfig',
  'firstBlend',
  'radialFieldConfig',
  'thirdBlend',
  'geometryConfig',
  'overlayBlend',
  'overlayAlpha',
  'overlayConfig'
];

function buildBundle(dir, label) {
  execSync('node build.js', { cwd: path.join(dir, 'render-service'), stdio: 'pipe' });
  return path.join(dir, 'render-service', 'generated', 'render-lib.js');
}

async function main() {
  console.log(`Comparing working tree against ${BASE}\n`);

  // A WORKTREE, not a stash. Stashing to build an old revision touches the working tree and
  // the shared stash stack -- which has already destroyed one of Aaron's stashes in this repo.
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'cf-render-base-'));
  const baseDir = path.join(tmp, 'base');
  let baseLib;
  try {
    execSync(`git -C "${REPO}" worktree add --detach "${baseDir}" ${BASE}`, { stdio: 'pipe' });
    // The old tree needs deps to bundle; reuse the current ones rather than a fresh install.
    // git checks out render-service/node_modules if that ref tracked any of it, so clear the
    // path first rather than assuming the worktree is bare there.
    const baseModules = path.join(baseDir, 'render-service', 'node_modules');
    fs.rmSync(baseModules, { recursive: true, force: true });
    fs.symlinkSync(path.join(REPO, 'render-service', 'node_modules'), baseModules);
    baseLib = buildBundle(baseDir, 'base');
    const headLib = buildBundle(REPO, 'head');

    const res = await fetch(
      `${SUPABASE_URL}/rest/v1/designs?select=id,data&limit=1000`,
      { headers: { apikey: ANON, Authorization: `Bearer ${ANON}` } }
    );
    if (!res.ok) throw new Error(`Supabase ${res.status}: ${await res.text()}`);
    const rows = (await res.json()).filter(r => r.data && r.data.seed);
    if (rows.length === 0) {
      console.error('No stored designs came back — refusing to report a pass on an empty set.');
      process.exit(1);
    }

    await import(path.join(REPO, 'render-service', 'shim.js'));
    const OLD = await import(`${baseLib}?t=${Date.now()}`);
    const NEW = await import(`${headLib}?t=${Date.now()}`);

    const changed = [];
    let starsChanged = 0;
    let geomLost = 0;
    let geomGained = 0;

    for (const row of rows) {
      const d = row.data;
      const fields = new Set();
      let starDiff = false;
      // Per DESIGN, not per design-x-size, or a loss reads as 3x its real size.
      let lostHere = false;
      let gainedHere = false;
      for (const [w, h] of SIZES) {
        const a = OLD.generateArtwork(d.seed, w, h, d.colors || [], d.settings || null);
        const b = NEW.generateArtwork(d.seed, w, h, d.colors || [], d.settings || null);
        for (const f of COMPOSITION_FIELDS) {
          if (JSON.stringify(a[f] ?? null) !== JSON.stringify(b[f] ?? null)) fields.add(f);
        }
        if (JSON.stringify(a.starFieldConfig) !== JSON.stringify(b.starFieldConfig)) starDiff = true;
        if (a.geometryConfig && !b.geometryConfig) lostHere = true;
        if (!a.geometryConfig && b.geometryConfig) gainedHere = true;
      }
      if (lostHere) geomLost++;
      if (gainedHere) geomGained++;
      if (fields.size) changed.push({ id: row.id.slice(0, 8), seed: d.seed, fields: [...fields] });
      if (starDiff) starsChanged++;
    }

    console.log(`${rows.length} stored designs x ${SIZES.length} sizes\n`);
    console.log(`  composition unchanged : ${rows.length - changed.length}`);
    console.log(`  composition CHANGED   : ${changed.length}`);
    console.log(`  geometry layer lost   : ${geomLost} designs`);
    console.log(`  geometry layer gained : ${geomGained} designs`);
    console.log(`  star field changed    : ${starsChanged}${ALLOW_STARS ? ' (allowed)' : ''}`);

    if (changed.length) {
      console.log('\nDesigns whose composition moved:');
      for (const c of changed.slice(0, 25)) {
        console.log(`  ${c.id}  seed ${c.seed}  ->  ${c.fields.join(', ')}`);
      }
      if (changed.length > 25) console.log(`  ... and ${changed.length - 25} more`);
      console.log(
        '\nFAIL: this change rewrites artwork people have already saved.\n' +
          'Move the new randomness onto its own rng stream (makeRng(`${seed}-<thing>`)) so the\n' +
          'shared sequence is untouched -- see this file\'s header for the incident this catches.'
      );
      process.exit(1);
    }

    if (starsChanged && !ALLOW_STARS) {
      console.log(
        '\nStar fields changed but --allow-stars was not passed. If that is intended, re-run\n' +
          'with --allow-stars; otherwise the star layer is moving when it should not be.'
      );
      process.exit(1);
    }

    console.log('\nPASS: every stored design still composes exactly as it did.');
  } finally {
    try {
      execSync(`git -C "${REPO}" worktree remove --force "${baseDir}"`, { stdio: 'pipe' });
    } catch {}
    // rmSync alone leaves the worktree registered, so a later run trips over stale entries.
    try {
      execSync(`git -C "${REPO}" worktree prune`, { stdio: 'pipe' });
    } catch {}
    fs.rmSync(tmp, { recursive: true, force: true });
  }
}

main().catch(e => {
  console.error(e);
  process.exit(1);
});
