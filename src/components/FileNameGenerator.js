export default function FileName() {
  let name =
    astroAdj[Math.floor(Math.random() * astroAdj.length)] +
    astroNouns[Math.floor(Math.random() * astroNouns.length)];
  const hex = Math.floor(Math.random() * 0xffff).toString(16).padStart(4, '0');

  name += '-' + hex;

  return name;
}
