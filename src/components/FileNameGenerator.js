/*
 * Export filenames: an astronomy/physics adjective + noun, plus 4 hex digits
 * (e.g. CoherentWavefront-1f3a). Used by DisplayCanvas for both the .jpg still and the
 * .mp4 animation export.
 *
 * Rules for adding words, so the pool stays usable:
 *  - ONE word, capitalized, no spaces or hyphens -- the two are concatenated directly.
 *  - Real astronomy, astrophysics, optics or particle-physics terminology. Not sci-fi, not
 *    mystical, not generic mechanics ('Torque', 'Velocity') -- the point is that a filename
 *    reads like it came off an observatory, and one loose word is what breaks that.
 *  - Never put the same word in BOTH arrays: it would then be able to pair with itself.
 *    'Quantum' used to be in both, which made 'QuantumQuantum' reachable; it is an adjective
 *    here now. Nothing is currently in both, so keep it that way.
 *  - A shared stem across the two arrays is fine and sometimes the point -- 'PlanetaryNebula',
 *    'SpiralGalaxy' and 'RadiantRadiance' are all reachable, and the first two are real terms.
 *  - Both arrays are sorted; keep them that way so a duplicate is easy to spot by eye.
 *
 * 110 adjectives x 109 nouns = 11,990 name stems,
 * x 65,536 hex suffixes = 785,776,640 filenames.
 */

